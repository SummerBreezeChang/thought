export function langFor(culture: Culture): Lang {
  return culture === "en-US" ? "en" : culture;
}

export function t(culture: Culture): Copy {
  return copy[langFor(culture)];
}

/** BCP-47 locale for Intl formatting. */
export function localeFor(culture: Culture): string {
  return culture;
}

export function reasonLabel(c: Copy, reasonKey: string): string {
  if (reasonKey === "rules.finishGoal") return c.finishGoal;
  if (reasonKey === "rules.mostOfGoal") return c.mostOfGoal;
  return c.classic;
}
